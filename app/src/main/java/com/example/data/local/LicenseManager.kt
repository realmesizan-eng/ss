package com.example.data.local

import java.security.MessageDigest
import kotlin.math.abs

object LicenseManager {
    private const val SALT = "PATHSHALA_01747570144_BD_2026"
    private const val ALPHABET = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ"

    /**
     * Generates a deterministic, checksum-verified license key in the format PS-XXXX-XXXX
     * from a seed (e.g., buyer phone + bKash TrxID).
     */
    fun generateLicenseKey(seedInput: String): String {
        val normalized = seedInput.trim().uppercase().ifBlank { "PATHSHALA100" }
        val digest = MessageDigest.getInstance("SHA-256")
            .digest("$normalized|$SALT".toByteArray())
        val codeChars = CharArray(4) { i ->
            val idx = abs(digest[i].toInt()) % ALPHABET.length
            ALPHABET[idx]
        }
        val body = String(codeChars)
        val check = computeChecksum(body)
        return "PS-$body-$check"
    }

    /**
     * Validates a license key generated by the Admin Panel (PS-XXXX-XXXX).
     */
    fun isValidLicenseKey(key: String): Boolean {
        val cleaned = key.trim().uppercase()
        val match = Regex("^PS-([A-Z2-9]{4})-([A-Z2-9]{4})$").matchEntire(cleaned) ?: return false
        val body = match.groupValues[1]
        val check = match.groupValues[2]
        return computeChecksum(body) == check
    }

    private fun computeChecksum(body: String): String {
        val digest = MessageDigest.getInstance("SHA-256")
            .digest("CHK|$body|$SALT".toByteArray())
        return buildString {
            for (i in 0 until 4) {
                val idx = abs(digest[i].toInt()) % ALPHABET.length
                append(ALPHABET[idx])
            }
        }
    }
}
